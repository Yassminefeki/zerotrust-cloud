def generate(policy: dict, env: dict, out: Path) -> dict[str, str]:
    errs = validate_policy(policy) + validate_env(env)
    if errs:
        raise PolicyError(errs)
    rules = resolve(policy)
    files: dict[str, str] = {}
    for node in policy["nodes"]:
        files[f"nodes/{node}/nftables.conf"] = render_node_nft(policy, node, rules)
        files[f"nodes/{node}/mtls.json"] = json.dumps(render_mtls(policy, node, rules), indent=2) + "\n"
    db = [s["node"] for s in policy["services"].values() if "db_user" in s]
    for d in set(db):
        files[f"nodes/{d}/pg_hba.conf"] = render_pg_hba(policy, rules)
        files[f"nodes/{d}/pg_ident.conf"] = render_pg_ident(policy, rules)
    files["host/nftables-zt.conf"] = render_host_nft(policy, env, rules)
    files["host/libvirt-hook-network"] = render_libvirt_hook(policy, env, rules)
    files["host/host.json"] = json.dumps({
        "wan_bridge": policy["networks"]["wan"]["bridge"],
        "wan_cidr": policy["networks"]["wan"]["cidr"],
        "zt_bridges": [s["bridge"] for s in policy["networks"].values() if "bridge" in s],
        "policy_cidrs": [s["cidr"] for s in policy["networks"].values()],
        "host_services": sorted({f"{r.proto}/{r.port}" for r in rules if r.dst.kind == "host"}),
        "dnat": [{"proto": r.proto, "to": f"{r.dst.addr}:{r.port}"} for r in rules if r.src.name == "internet"],
    }, indent=2) + "\n"
    for name, text in render_wireguard(policy, env).items():
        files[f"wireguard/{name}"] = text
    files["terraform.tfvars.json"] = json.dumps(render_tfvars(policy, env), indent=2) + "\n"
    files["inventory.yml"] = GENERATED_HEADER + yaml.safe_dump(render_inventory(policy, env), sort_keys=False)
    files["ssh_config"] = render_ssh_config(policy, env)
    files["matrix.json"] = json.dumps(render_matrix(policy, rules), indent=2) + "\n"
    files["flows.json"] = json.dumps([asdict(r) for r in rules], indent=2) + "\n"
    for rel, text in files.items():
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--policy", default=ROOT / "policy.yaml", type=Path)
    ap.add_argument("--env", default=ROOT / "env.yaml", type=Path)
    ap.add_argument("--out", default=ROOT / "build", type=Path)
    ap.add_argument("--check", action="store_true", help="validate only, write nothing")
    a = ap.parse_args(argv)
    if not a.env.exists():
        print(f"error: {a.env} not found. Run: cp env.example.yaml env.yaml && edit it", file=sys.stderr)
        return 2
    try:
        policy, env = load_yaml(a.policy), load_yaml(a.env)
        if a.check:
            errs = validate_policy(policy) + validate_env(env)
            if errs:
                raise PolicyError(errs)
            resolve(policy)
            print("policy OK")
            return 0
        files = generate(policy, env, a.out)
    except PolicyError as e:
        print(f"policy error:\n{e}", file=sys.stderr)
        return 1
    m = json.loads(files["matrix.json"])
    print(f"generated {len(files)} files in {a.out}  "
          f"({sum(1 for x in m if x['expected'] == 'allow')} allowed / {len(m)} probes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
