#!/usr/bin/env python3
"""
gen_rules.py — policy.yaml + env.yaml  ->  everything that enforces the policy.

Outputs (under --out, default build/; the directory is gitignored):

  nodes/<node>/nftables.conf     default-drop ruleset for each VM (input/forward/output)
  nodes/<node>/mtls.json         services served by the node + allowed SPIFFE IDs,
                                 upstreams it calls + the SPIFFE ID they must present
  nodes/database/pg_hba.conf     PostgreSQL access, derived from the service-b->database flow
  host/nftables-zt.conf          host-side DNAT (by interface NAME) + mgmt accepts
  wireguard/gateway-wg0.conf.j2  server config (Jinja: keys injected by Ansible)
  wireguard/client-<peer>.conf.j2  client config templates (i7 export, test-peer)
  terraform.tfvars.json          networks + VMs for Terraform (IPs, MACs, memory, routes)
  inventory.yml                  Ansible inventory (mgmt addresses)
  matrix.json                    NxN probe matrix with the expected verdict per pair
  flows.json                     resolved flows (debug / documentation)

Usage:
  tools/gen_rules.py --policy policy.yaml --env env.yaml --out build/
  tools/gen_rules.py --check             # validate only
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import re
import sys
from dataclasses import dataclass, field, asdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
GENERATED_HEADER = "# GENERATED by tools/gen_rules.py from policy.yaml — DO NOT EDIT\n"
LOG_RATE = "limit rate 10/second burst 20 packets"
IFNAME_RE = re.compile(r"^[A-Za-z0-9_.\-]{1,15}$")
HOSTNAME_RE = re.compile(r"^(?=.{1,253}$)([A-Za-z0-9]([A-Za-z0-9\-]{0,61}[A-Za-z0-9])?)(\.[A-Za-z0-9]([A-Za-z0-9\-]{0,61}[A-Za-z0-9])?)*$")
ENV_REQUIRED = ["entry_point", "wan_interface", "wan_port", "libvirt_uri", "libvirt_pool_name",
                "libvirt_pool_path", "ubuntu_image_url", "ssh_user", "ssh_public_key_file"]


class PolicyError(Exception):
    def __init__(self, errors):
        self.errors = errors if isinstance(errors, list) else [errors]
        super().__init__("\n".join(f"  - {e}" for e in self.errors))


# --------------------------------------------------------------------------- #
# Loading & validation
# --------------------------------------------------------------------------- #
def load_yaml(path: Path) -> dict:
    with open(path) as fh:
        data = yaml.safe_load(fh)
    if not isinstance(data, dict):
        raise PolicyError(f"{path}: top level must be a mapping")
    return data


def spiffe(policy: dict, name: str) -> str:
    return f"spiffe://{policy['trust_domain']}/{name}"


def validate_env(env: dict) -> list[str]:
    errs = []
    for k in ENV_REQUIRED:
        if k not in env or env[k] in (None, ""):
            errs.append(f"env: missing key '{k}'")
    ep = str(env.get("entry_point", ""))
    try:
        ipaddress.ip_address(ep)
        errs.append(f"env: entry_point must be a hostname (e.g. cloud-i5.local), not an IP ('{ep}')")
    except ValueError:
        if ep and not HOSTNAME_RE.match(ep):
            errs.append(f"env: entry_point '{ep}' is not a valid hostname")
    if not str(env.get("ssh_public_key_file", "")).endswith(".pub"):
        errs.append("env: ssh_public_key_file must be the PUBLIC key (*.pub)")
    wi = str(env.get("wan_interface", ""))
    if wi and not IFNAME_RE.match(wi):
        errs.append(f"env: wan_interface '{wi}' is not a valid interface name")
    try:
        p = int(env.get("wan_port", 0))
        if not 1 <= p <= 65535:
            raise ValueError
    except (TypeError, ValueError):
        errs.append(f"env: wan_port '{env.get('wan_port')}' must be 1..65535")
    return errs


def validate_policy(policy: dict) -> list[str]:
    errs: list[str] = []
    if policy.get("version") != 1:
        errs.append("policy: version must be 1")
    for key in ("trust_domain", "networks", "nodes", "principals", "services", "flows"):
        if key not in policy:
            errs.append(f"policy: missing '{key}'")
    if errs:
        return errs

    nets = policy["networks"]
    cidrs = {}
    for n, spec in nets.items():
        try:
            cidrs[n] = ipaddress.ip_network(spec["cidr"])
        except (KeyError, ValueError) as e:
            errs.append(f"network {n}: bad cidr ({e})")
            continue
        if spec.get("mode") not in ("nat", "isolated", "wireguard"):
            errs.append(f"network {n}: mode must be nat|isolated|wireguard")
        if not IFNAME_RE.match(str(spec.get("iface", ""))):
            errs.append(f"network {n}: bad iface name")
        if spec.get("mode") != "wireguard" and not IFNAME_RE.match(str(spec.get("bridge", ""))):
            errs.append(f"network {n}: bridge name missing or longer than 15 chars")
        if "host_ip" in spec and ipaddress.ip_address(spec["host_ip"]) not in cidrs[n]:
            errs.append(f"network {n}: host_ip outside cidr")
    if "mgmt" not in nets:
        errs.append("policy: a 'mgmt' network is required")

    seen_ips: dict[str, str] = {}
    for spec_n, spec in nets.items():
        if "host_ip" in spec:
            seen_ips[spec["host_ip"]] = f"host@{spec_n}"
    ids = set()
    for node, spec in policy["nodes"].items():
        if spec.get("id") in ids:
            errs.append(f"node {node}: duplicate id {spec.get('id')}")
        ids.add(spec.get("id"))
        if "mgmt" not in spec.get("interfaces", {}):
            errs.append(f"node {node}: every VM needs a mgmt interface")
        for net, ip in spec.get("interfaces", {}).items():
            if net not in cidrs:
                errs.append(f"node {node}: unknown network '{net}'")
                continue
            try:
                addr = ipaddress.ip_address(ip)
            except ValueError:
                errs.append(f"node {node}: bad IP {ip}")
                continue
            if addr not in cidrs[net]:
                errs.append(f"node {node}: {ip} is not in {net} {cidrs[net]}")
            if ip in seen_ips:
                errs.append(f"node {node}: IP {ip} already used by {seen_ips[ip]}")
            seen_ips[ip] = node

    for p, spec in policy["principals"].items():
        if p in policy["nodes"]:
            errs.append(f"principal {p}: name clashes with a node")
        if spec.get("network") not in nets:
            errs.append(f"principal {p}: unknown network")
        for ident in spec.get("identities", []):
            if not ident.startswith(f"spiffe://{policy['trust_domain']}/"):
                errs.append(f"principal {p}: identity {ident} is outside trust domain")

    for s, spec in policy["services"].items():
        if spec.get("network") not in nets:
            errs.append(f"service {s}: unknown network")
        if spec.get("proto") not in ("tcp", "udp"):
            errs.append(f"service {s}: proto must be tcp|udp")
        if not isinstance(spec.get("port"), int) or not 1 <= spec["port"] <= 65535:
            errs.append(f"service {s}: bad port")
        node = spec.get("node")
        if node not in ("*", "host") and node not in policy["nodes"]:
            errs.append(f"service {s}: unknown node {node}")
        elif node in policy["nodes"] and spec.get("network") not in policy["nodes"][node]["interfaces"]:
            errs.append(f"service {s}: node {node} has no interface on {spec.get('network')}")
        if node == "host" and "host_ip" not in nets.get(spec.get("network"), {}):
            errs.append(f"service {s}: host has no IP on {spec.get('network')}")

    known_src = set(policy["nodes"]) | set(policy["principals"])
    names = set()
    for section in ("flows", "infra"):
        for f in policy.get(section, []):
            if f.get("name") in names:
                errs.append(f"{section}: duplicate flow name {f.get('name')}")
            names.add(f.get("name"))
            if f.get("from") != "*" and f.get("from") not in known_src:
                errs.append(f"{section} {f.get('name')}: unknown source {f.get('from')}")
            if f.get("to") not in policy["services"]:
                errs.append(f"{section} {f.get('name')}: unknown service {f.get('to')}")
                continue
            svc_net = policy["services"][f["to"]]["network"]
            # The management plane must never carry business traffic and vice-versa.
            if section == "infra" and svc_net != "mgmt":
                errs.append(f"infra {f['name']}: infra flows must stay on the mgmt network")
            if section == "flows" and svc_net == "mgmt":
                errs.append(f"flow {f['name']}: business flows may not use the mgmt network")

    tun = cidrs.get("tunnel")
    peer_ips = set()
    for peer in policy.get("wireguard", {}).get("peers", []):
        ip = ipaddress.ip_address(peer["ip"])
        if tun and ip not in tun:
            errs.append(f"wireguard peer {peer['name']}: {ip} not in tunnel network")
        if peer["ip"] in peer_ips or peer["ip"] in seen_ips:
            errs.append(f"wireguard peer {peer['name']}: duplicate IP {ip}")
        peer_ips.add(peer["ip"])
    return errs


# --------------------------------------------------------------------------- #
# Flow resolution
# --------------------------------------------------------------------------- #
@dataclass
class Endpoint:
    kind: str            # node | principal
    name: str
    addr: str            # IP or CIDR as seen on the wire
    network: str
    iface: str | None    # interface name on the VM (None for principals)


@dataclass
class Rule:
    name: str
    section: str         # flows | infra
    service: str
    src: Endpoint
    dst: Endpoint        # dst.kind: node | host
    port: int
    proto: str
    router: str | None = None
    router_in: str | None = None
    router_out: str | None = None
    mtls: bool = False
    allowed_ids: list[str] = field(default_factory=list)


def _src_endpoint(policy, name, network_hint):
    nets = policy["networks"]
    if name in policy["nodes"]:
        node = policy["nodes"][name]
        if network_hint in node["interfaces"]:
            return Endpoint("node", name, node["interfaces"][network_hint], network_hint,
                            nets[network_hint]["iface"])
        return None
    p = policy["principals"][name]
    return Endpoint("principal", name, p["cidr"], p["network"], None)


def _dst_endpoints(policy, svc_name):
    svc = policy["services"][svc_name]
    net = svc["network"]
    nets = policy["networks"]
    if svc["node"] == "host":
        return [Endpoint("host", "host", nets[net]["host_ip"], net, nets[net].get("bridge"))]
    targets = policy["nodes"] if svc["node"] == "*" else [svc["node"]]
    out = []
    for t in targets:
        ifs = policy["nodes"][t]["interfaces"]
        if net in ifs:
            out.append(Endpoint("node", t, ifs[net], net, nets[net]["iface"]))
    return out


def _identities(policy, src_name):
    if src_name in policy["nodes"]:
        return [spiffe(policy, src_name)]
    return list(policy["principals"][src_name].get("identities", []))


def resolve(policy: dict) -> list[Rule]:
    rules: list[Rule] = []
    errs: list[str] = []
    for section in ("flows", "infra"):
        for f in policy.get(section, []):
            svc = policy["services"][f["to"]]
            sources = (list(policy["nodes"]) if f["from"] == "*" else [f["from"]])
            for dst in _dst_endpoints(policy, f["to"]):
                for s in sources:
                    if dst.kind == "node" and s == dst.name:
                        continue  # a node talking to itself uses loopback
                    src = _src_endpoint(policy, s, dst.network)
                    router = rin = rout = None
                    if src is None or src.network != dst.network:
                        # Need a router: a VM with interfaces on both networks.
                        src_net = (policy["principals"][s]["network"] if s in policy["principals"] else None)
                        if src_net is None:
                            errs.append(f"{f['name']}: {s} shares no network with {dst.name} "
                                        f"({dst.network}) and nodes are never routed")
                            continue
                        routers = [n for n, spec in policy["nodes"].items()
                                   if src_net in spec["interfaces"] and dst.network in spec["interfaces"]]
                        if not routers:
                            errs.append(f"{f['name']}: no router between {src_net} and {dst.network}")
                            continue
                        router = routers[0]
                        if not policy["nodes"][router].get("ip_forward"):
                            errs.append(f"{f['name']}: router {router} has ip_forward disabled")
                            continue
                        rin = policy["networks"][src_net]["iface"]
                        rout = policy["networks"][dst.network]["iface"]
                    rules.append(Rule(
                        name=f["name"], section=section, service=f["to"], src=src, dst=dst,
                        port=svc["port"], proto=svc["proto"], router=router,
                        router_in=rin, router_out=rout, mtls=bool(svc.get("mtls")),
                        allowed_ids=_identities(policy, s) if svc.get("mtls") else []))
    if errs:
        raise PolicyError(errs)
    return rules


