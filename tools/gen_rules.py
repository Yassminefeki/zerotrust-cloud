@dataclass
class Endpoint:
    kind: str            # node | principal
    name: str
    addr: str            # IP or CIDR as seen on the wire
    network: str
    iface: str | None    # interface name on the VM (None for principals)


@dataclass
class Rule:
    name: str
    section: str         # flows | infra
    service: str
    src: Endpoint
    dst: Endpoint        # dst.kind: node | host
    port: int
    proto: str
    router: str | None = None
    router_in: str | None = None
    router_out: str | None = None
    mtls: bool = False
    allowed_ids: list[str] = field(default_factory=list)
    # published from the internet THROUGH a router (not a VPN): the router DNATs `published`
    # (its own address on the source network) to dst, and SNATs to `snat` (its address on the
    # destination network), so the destination sees, and answers, the router only.
    published: str | None = None
    snat: str | None = None


def _src_endpoint(policy, name, network_hint):
    nets = policy["networks"]
    if name in policy["nodes"]:
        node = policy["nodes"][name]
        if network_hint in node["interfaces"]:
            return Endpoint("node", name, node["interfaces"][network_hint], network_hint,
                            nets[network_hint]["iface"])
        return None
    p = policy["principals"][name]
    return Endpoint("principal", name, p["cidr"], p["network"], None)


def _dst_endpoints(policy, svc_name):
    svc = policy["services"][svc_name]
    net = svc["network"]
    nets = policy["networks"]
    if svc["node"] == "host":
        return [Endpoint("host", "host", nets[net]["host_ip"], net, nets[net].get("bridge"))]
    targets = policy["nodes"] if svc["node"] == "*" else [svc["node"]]
    out = []
    for t in targets:
        ifs = policy["nodes"][t]["interfaces"]
        if net in ifs:
            out.append(Endpoint("node", t, ifs[net], net, nets[net]["iface"]))
    return out


def actor_uri(policy, name):
    return spiffe(policy, f"{policy['actors'][name]['role']}/{name}")


def _identities(policy, src_name):
    if src_name in policy["nodes"]:
        return [spiffe(policy, src_name)]
    # a principal presents the identities of the actors that enter through it
    return [actor_uri(policy, a) for a, spec in policy.get("actors", {}).items()
            if spec.get("entry") == src_name]


def expand_allow(policy, who_list):
    """Route allow entries (roles, node names) -> concrete SPIFFE IDs."""
    out = []
    for who in who_list:
        if who in policy.get("roles", {}):
            out += [actor_uri(policy, a) for a, spec in policy["actors"].items() if spec["role"] == who]
        else:
            out.append(spiffe(policy, who))
    return out


def resolve(policy: dict) -> list[Rule]:
    rules: list[Rule] = []
    errs: list[str] = []
    for section in ("flows", "infra"):
        for f in policy.get(section, []):
            svc = policy["services"][f["to"]]
            sources = (list(policy["nodes"]) if f["from"] == "*" else [f["from"]])
            for dst in _dst_endpoints(policy, f["to"]):
                for s in sources:
                    if dst.kind == "node" and s == dst.name:
                        continue  # a node talking to itself uses loopback
                    src = _src_endpoint(policy, s, dst.network)
                    router = rin = rout = None
                    if src is None or src.network != dst.network:
                        # Need a router: a VM with interfaces on both networks.
                        src_net = (policy["principals"][s]["network"] if s in policy["principals"] else None)
                        if src_net is None:
                            errs.append(f"{f['name']}: {s} shares no network with {dst.name} "
                                        f"({dst.network}) and nodes are never routed")
                            continue
                        routers = [n for n, spec in policy["nodes"].items()
                                   if src_net in spec["interfaces"] and dst.network in spec["interfaces"]]
                        if not routers:
                            errs.append(f"{f['name']}: no router between {src_net} and {dst.network}")
                            continue
                        router = routers[0]
                        if not policy["nodes"][router].get("ip_forward"):
                            errs.append(f"{f['name']}: router {router} has ip_forward disabled")
                            continue
                        rin = policy["networks"][src_net]["iface"]
                        rout = policy["networks"][dst.network]["iface"]
                    published = snat = None
                    if router and src.addr == "0.0.0.0/0":
                        r_ifs = policy["nodes"][router]["interfaces"]
                        published, snat = r_ifs[src.network], r_ifs[dst.network]
                    rules.append(Rule(
                        name=f["name"], section=section, service=f["to"], src=src, dst=dst,
                        port=svc["port"], proto=svc["proto"], router=router,
                        router_in=rin, router_out=rout, mtls=bool(svc.get("mtls")),
                        allowed_ids=_identities(policy, s) if svc.get("mtls") else [],
                        published=published, snat=snat))
    if errs:
        raise PolicyError(errs)
    return rules


