def load_yaml(path: Path) -> dict:
    with open(path) as fh:
        data = yaml.safe_load(fh)
    if not isinstance(data, dict):
        raise PolicyError(f"{path}: top level must be a mapping")
    return data


def spiffe(policy: dict, name: str) -> str:
    return f"spiffe://{policy['trust_domain']}/{name}"


def validate_env(env: dict) -> list[str]:
    errs = []
    for k in ENV_REQUIRED:
        if k not in env or env[k] in (None, ""):
            errs.append(f"env: missing key '{k}'")
    ep = str(env.get("entry_point", ""))
    try:
        ipaddress.ip_address(ep)
        errs.append(f"env: entry_point must be a hostname (e.g. cloud-i5.local), not an IP ('{ep}')")
    except ValueError:
        if ep and not HOSTNAME_RE.match(ep):
            errs.append(f"env: entry_point '{ep}' is not a valid hostname")
    if not str(env.get("ssh_public_key_file", "")).endswith(".pub"):
        errs.append("env: ssh_public_key_file must be the PUBLIC key (*.pub)")
    wi = str(env.get("wan_interface", ""))
    if wi and not IFNAME_RE.match(wi):
        errs.append(f"env: wan_interface '{wi}' is not a valid interface name")
    try:
        p = int(env.get("wan_port", 0))
        if not 1 <= p <= 65535:
            raise ValueError
    except (TypeError, ValueError):
        errs.append(f"env: wan_port '{env.get('wan_port')}' must be 1..65535")
    return errs


def validate_policy(policy: dict) -> list[str]:
    errs: list[str] = []
    if policy.get("version") != 1:
        errs.append("policy: version must be 1")
    for key in ("trust_domain", "networks", "nodes", "principals", "services", "flows"):
        if key not in policy:
            errs.append(f"policy: missing '{key}'")
    if errs:
        return errs

    nets = policy["networks"]
    cidrs = {}
    for n, spec in nets.items():
        try:
            cidrs[n] = ipaddress.ip_network(spec["cidr"])
        except (KeyError, ValueError) as e:
            errs.append(f"network {n}: bad cidr ({e})")
            continue
        if spec.get("mode") not in ("nat", "isolated", "wireguard"):
            errs.append(f"network {n}: mode must be nat|isolated|wireguard")
        if not IFNAME_RE.match(str(spec.get("iface", ""))):
            errs.append(f"network {n}: bad iface name")
        if spec.get("mode") != "wireguard" and not IFNAME_RE.match(str(spec.get("bridge", ""))):
            errs.append(f"network {n}: bridge name missing or longer than 15 chars")
        if "host_ip" in spec and ipaddress.ip_address(spec["host_ip"]) not in cidrs[n]:
            errs.append(f"network {n}: host_ip outside cidr")
    if "mgmt" not in nets:
        errs.append("policy: a 'mgmt' network is required")

    seen_ips: dict[str, str] = {}
    for spec_n, spec in nets.items():
        if "host_ip" in spec:
            seen_ips[spec["host_ip"]] = f"host@{spec_n}"
    ids = set()
    for node, spec in policy["nodes"].items():
        if spec.get("id") in ids:
            errs.append(f"node {node}: duplicate id {spec.get('id')}")
        ids.add(spec.get("id"))
        if "mgmt" not in spec.get("interfaces", {}):
            errs.append(f"node {node}: every VM needs a mgmt interface")
        for net, ip in spec.get("interfaces", {}).items():
            if net not in cidrs:
                errs.append(f"node {node}: unknown network '{net}'")
                continue
            try:
                addr = ipaddress.ip_address(ip)
            except ValueError:
                errs.append(f"node {node}: bad IP {ip}")
                continue
            if addr not in cidrs[net]:
                errs.append(f"node {node}: {ip} is not in {net} {cidrs[net]}")
            if ip in seen_ips:
                errs.append(f"node {node}: IP {ip} already used by {seen_ips[ip]}")
            seen_ips[ip] = node

    for p, spec in policy["principals"].items():
        if p in policy["nodes"]:
            errs.append(f"principal {p}: name clashes with a node")
        if spec.get("network") not in nets:
            errs.append(f"principal {p}: unknown network")
        for ident in spec.get("identities", []):
            if not ident.startswith(f"spiffe://{policy['trust_domain']}/"):
                errs.append(f"principal {p}: identity {ident} is outside trust domain")

    for s, spec in policy["services"].items():
        if spec.get("network") not in nets:
            errs.append(f"service {s}: unknown network")
        if spec.get("proto") not in ("tcp", "udp"):
            errs.append(f"service {s}: proto must be tcp|udp")
        if not isinstance(spec.get("port"), int) or not 1 <= spec["port"] <= 65535:
            errs.append(f"service {s}: bad port")
        node = spec.get("node")
        if node not in ("*", "host") and node not in policy["nodes"]:
            errs.append(f"service {s}: unknown node {node}")
        elif node in policy["nodes"] and spec.get("network") not in policy["nodes"][node]["interfaces"]:
            errs.append(f"service {s}: node {node} has no interface on {spec.get('network')}")
        if node == "host" and "host_ip" not in nets.get(spec.get("network"), {}):
            errs.append(f"service {s}: host has no IP on {spec.get('network')}")

    known_src = set(policy["nodes"]) | set(policy["principals"])
    names = set()
    for section in ("flows", "infra"):
        for f in policy.get(section, []):
            if f.get("name") in names:
                errs.append(f"{section}: duplicate flow name {f.get('name')}")
            names.add(f.get("name"))
            if f.get("from") != "*" and f.get("from") not in known_src:
                errs.append(f"{section} {f.get('name')}: unknown source {f.get('from')}")
            if f.get("to") not in policy["services"]:
                errs.append(f"{section} {f.get('name')}: unknown service {f.get('to')}")
                continue
            svc_net = policy["services"][f["to"]]["network"]
            # The management plane must never carry business traffic and vice-versa.
            if section == "infra" and svc_net != "mgmt":
                errs.append(f"infra {f['name']}: infra flows must stay on the mgmt network")
            if section == "flows" and svc_net == "mgmt":
                errs.append(f"flow {f['name']}: business flows may not use the mgmt network")

    tun = cidrs.get("tunnel")
    peer_ips = set()
    for peer in policy.get("wireguard", {}).get("peers", []):
        ip = ipaddress.ip_address(peer["ip"])
        if tun and ip not in tun:
            errs.append(f"wireguard peer {peer['name']}: {ip} not in tunnel network")
        if peer["ip"] in peer_ips or peer["ip"] in seen_ips:
            errs.append(f"wireguard peer {peer['name']}: duplicate IP {ip}")
        if not isinstance(peer.get("test", False), bool):
            errs.append(f"wireguard peer {peer['name']}: test must be true/false")
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,30}", str(peer["name"])):
            errs.append(f"wireguard peer {peer['name']}: name must be a lowercase DNS label")
        if "netns" in peer and not re.fullmatch(r"zt-[a-z0-9-]{1,8}", str(peer["netns"])):
            errs.append(f"wireguard peer {peer['name']}: netns must look like zt-<name> (max 11 chars)")
        if "conn_limit" in peer:
            m = RATE_RE.match(str(peer["conn_limit"]))
            if not m or m.group(2) not in ("s", "second"):
                errs.append(f"wireguard peer {peer['name']}: conn_limit must look like 5/second")
        peer_ips.add(peer["ip"])
    peers = policy.get("wireguard", {}).get("peers", [])
    if peers and not any(not p.get("test") for p in peers):
        errs.append("wireguard: at least one real (non-test) peer is required")
    errs += validate_actors_and_routes(policy)
    return errs


METHODS = {"GET", "POST", "PUT", "PATCH", "DELETE"}
APPS = {"web", "core", "ledger", "partner"}
RATE_RE = re.compile(r"^([1-9][0-9]{0,5})/(s|second|min|minute|h|hour)$")
PER_MIN = {"s": 60, "second": 60, "min": 1, "minute": 1, "h": 1 / 60, "hour": 1 / 60}


def per_minute(rate: str) -> float:
    """'240/min' -> 240.0, '5/second' -> 300.0"""
    m = RATE_RE.match(str(rate))
    if not m:
        raise ValueError(rate)
    return int(m.group(1)) * PER_MIN[m.group(2)]
AMOUNT_RE = re.compile(r"\d{1,9}(\.\d{1,2})?")


def cents(amount: str) -> int:
    """\"12.3\" -> 1230. Exact (no float)."""
    whole, _, frac = str(amount).partition(".")
    return int(whole) * 100 + int((frac + "00")[:2])


def partner_account(name: str) -> str:
    return f"ZTB-{name.upper().replace('-', '')[:12]}-00"


def render_bank(policy: dict) -> dict:
    """Business limits + customers, for the services and the database seed."""
    b = policy.get("bank", {})
    return {"currency": b.get("currency", "EUR"),
            "max_transfer_cents": cents(b.get("max_transfer", "0")),
            "daily_limit_cents": cents(b.get("daily_limit", "0")),
            "webhook_max_skew_s": policy.get("webhook", {}).get("max_skew_seconds", 300),
            "customers": [{"id": a["customer"], "full_name": a["full_name"]}
                          for a in policy.get("actors", {}).values() if a.get("role") == "customer"],
            # each payment partner settles through its own account of the bank
            "partners": [{"id": n, "name": a.get("full_name", n), "account": partner_account(n),
                          "identity": actor_uri(policy, n)}
                         for n, a in policy.get("actors", {}).items() if a.get("role") == "partner"]}


LIFETIME_RE = re.compile(r"^(\d+)([hm])$")


def _hours(lifetime: str) -> float:
    m = LIFETIME_RE.match(str(lifetime))
    if not m:
        raise ValueError(lifetime)
    return int(m.group(1)) / (1 if m.group(2) == "h" else 60)


def _callers(policy: dict, service: str) -> set[str]:
    """Sources that reach `service` through a declared flow (principals and nodes)."""
    return {f["from"] for f in policy.get("flows", []) if f["to"] == service}


def validate_actors_and_routes(policy: dict) -> list[str]:
    errs: list[str] = []
    roles = policy.get("roles", {})
    actors = policy.get("actors", {})
    peers = {p["name"]: p for p in policy.get("wireguard", {}).get("peers", [])}
    max_h = _hours(policy["cert"]["lifetime"])
    for name, a in actors.items():
        if not re.fullmatch(r"[a-z][a-z0-9-]{0,30}", name):
            errs.append(f"actor {name}: name must be a lowercase DNS label")
        if a.get("role") not in roles:
            errs.append(f"actor {name}: unknown role {a.get('role')}")
        if a.get("entry") not in policy["principals"]:
            errs.append(f"actor {name}: entry must be a principal (e.g. tunnel)")
        if (a.get("role") == "customer") != ("customer" in a):
            errs.append(f"actor {name}: `customer` is required for, and only for, role customer")
        if "export_to" in a and (a["export_to"] not in peers or peers[a["export_to"]].get("test")):
            errs.append(f"actor {name}: export_to must be a real (non-test) WireGuard peer")
        if "device" in a:
            if a.get("entry") != "tunnel":
                errs.append(f"actor {name}: device binds a tunnel identity to a WireGuard peer (entry: tunnel)")
            elif a["device"] not in peers or peers[a["device"]].get("test"):
                errs.append(f"actor {name}: device must be a real (non-test) WireGuard peer")
        if a.get("role") == "partner" and a.get("entry") != "internet":
            errs.append(f"actor {name}: partners come from the internet (entry: internet), not through the VPN")
        if "cert_lifetime" in a:
            try:
                if _hours(a["cert_lifetime"]) > max_h:
                    errs.append(f"actor {name}: cert_lifetime above the CA maximum {policy['cert']['lifetime']}")
            except ValueError:
                errs.append(f"actor {name}: cert_lifetime must look like 1h or 30m")
    for name, a in actors.items():
        if a.get("role") == "customer" and not str(a.get("full_name", "")).strip():
            errs.append(f"actor {name}: customers need a full_name (shown in the bank)")
    for svc_name, svc in policy["services"].items():
        if "app" in svc and svc["app"] not in APPS:
            errs.append(f"service {svc_name}: app must be one of {sorted(APPS)}")
    for rname, r in roles.items():
        if "rate_limit" in r and not RATE_RE.match(str(r["rate_limit"])):
            errs.append(f"role {rname}: rate_limit must look like 240/min")
    skew = policy.get("webhook", {}).get("max_skew_seconds", 300)
    if not isinstance(skew, int) or not 30 <= skew <= 3600:
        errs.append("webhook: max_skew_seconds must be an integer between 30 and 3600")
    bank = policy.get("bank")
    if bank is not None:
        if not re.fullmatch(r"[A-Z]{3}", str(bank.get("currency", ""))):
            errs.append("bank: currency must be a 3-letter ISO code")
        for k in ("max_transfer", "daily_limit"):
            if not AMOUNT_RE.fullmatch(str(bank.get(k, ""))):
                errs.append(f"bank: {k} must be an amount like \"2000.00\"")
    routes = policy.get("routes", {})
    for svc_name, svc in policy["services"].items():
        if svc.get("mtls") and "db_user" not in svc and svc_name not in routes:
            errs.append(f"routes: mTLS service {svc_name} has no routes (nothing would be reachable)")
    for svc_name, rlist in routes.items():
        svc = policy["services"].get(svc_name)
        if not svc or not svc.get("mtls") or "db_user" in svc:
            errs.append(f"routes {svc_name}: routes apply to HTTPS mTLS services only")
            continue
        callers = _callers(policy, svc_name)
        seen = set()
        for r in rlist:
            key = (r.get("method"), r.get("path"))
            label = f"routes {svc_name} {r.get('method')} {r.get('path')}"
            if key in seen:
                errs.append(f"{label}: duplicate")
            seen.add(key)
            if r.get("method") not in METHODS:
                errs.append(f"{label}: method must be one of {sorted(METHODS)}")
            if not str(r.get("path", "")).startswith("/"):
                errs.append(f"{label}: path must start with /")
            if not r.get("allow"):
                errs.append(f"{label}: empty allow list")
            for who in r.get("allow", []):
                if who in roles:
                    reach = [a for a, spec in actors.items()
                             if spec.get("role") == who and spec.get("entry") in callers]
                    if not reach:
                        errs.append(f"{label}: no actor of role {who} reaches {svc_name} through a flow")
                elif who in policy["nodes"]:
                    if who not in callers:
                        errs.append(f"{label}: node {who} has no flow to {svc_name}")
                else:
                    errs.append(f"{label}: allow entry {who} is neither a role nor a node")
    return errs


