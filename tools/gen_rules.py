# Renderers
# --------------------------------------------------------------------------- #
def _saddr(ep: Endpoint) -> str:
    return "" if ep.addr == "0.0.0.0/0" else f"ip saddr {ep.addr} "


def render_node_nft(policy: dict, node: str, rules: list[Rule]) -> str:
    inp, fwd, out = [], [], []
    for r in rules:
        match = f"{r.proto} dport {r.port}"
        c = f'comment "{r.section}:{r.name}"'
        if r.dst.kind == "node" and r.dst.name == node:
            iif = r.dst.iface
            inp.append(f'iifname "{iif}" {_saddr(r.src)}ip daddr {r.dst.addr} {match} ct state new accept {c}')
            if r.proto == "udp":
                # UDP server (WireGuard) may originate handshakes from its port after conntrack expiry.
                out.append(f'oifname "{iif}" ip saddr {r.dst.addr} udp sport {r.port} accept {c}')
        if r.src.kind == "node" and r.src.name == node:
            out.append(f'oifname "{r.src.iface}" ip saddr {r.src.addr} ip daddr {r.dst.addr} {match} '
                       f'ct state new accept {c}')
        if r.router == node:
            fwd.append(f'iifname "{r.router_in}" oifname "{r.router_out}" {_saddr(r.src)}'
                       f'ip daddr {r.dst.addr} {match} ct state new accept {c}')

    def chain(name, hook, body, lo):
        lines = [f"  chain {name} {{",
                 f"    type filter hook {hook} priority filter; policy drop;",
                 "    ct state invalid drop",
                 "    ct state established,related accept"]
        if lo:
            lines.append(f'    {lo} "lo" accept')
        lines += [f"    {b}" for b in body]
        lines.append(f'    {LOG_RATE} log prefix "zt-drop-{name}: " level warn')
        lines.append("  }")
        return lines

    text = [GENERATED_HEADER.rstrip(), f"# node: {node}", "flush ruleset", "",
            "table inet zt {"]
    text += chain("input", "input", inp, "iifname")
    text.append("")
    text += chain("forward", "forward", fwd, None)
    text.append("")
    text += chain("output", "output", out, "oifname")
    text.append("}")
    return "\n".join(text) + "\n"


def render_host_nft(policy: dict, env: dict, rules: list[Rule]) -> str:
    """Host side: never default-drop the user's laptop. Only adds what the cloud needs."""
    nets = policy["networks"]
    wg = [r for r in rules if r.src.name == "internet"]
    lines = [GENERATED_HEADER.rstrip(),
             "# Host (i5) rules. Matches the WAN side by interface NAME, never by IP,",
             "# so changing Wi-Fi network needs no change here.",
             "table inet zt_host",
             "delete table inet zt_host", "",
             "table inet zt_host {",
             "  chain prerouting {",
             "    type nat hook prerouting priority dstnat; policy accept;"]
    for r in wg:
        lines.append(f'    iifname "{env["wan_interface"]}" {r.proto} dport {int(env["wan_port"])} '
                     f'dnat ip to {r.dst.addr}:{r.port} comment "flows:{r.name}"')
    lines += ["  }", "",
              "  chain forward {",
              "    type filter hook forward priority filter - 10; policy accept;"]
    for r in wg:
        lines.append(f'    iifname "{env["wan_interface"]}" oifname "{nets[r.dst.network]["bridge"]}" '
                     f'ip daddr {r.dst.addr} {r.proto} dport {r.port} ct status dnat accept '
                     f'comment "flows:{r.name}"')
    lines += ["  }", "",
              "  chain input {",
              "    type filter hook input priority filter - 10; policy accept;"]
    host_ports = set()
    for r in rules:
        if r.dst.kind == "host":
            host_ports.add((r.proto, r.port))
            lines.append(f'    iifname "{r.dst.iface}" ip saddr {r.src.addr} ip daddr {r.dst.addr} '
                         f'{r.proto} dport {r.port} accept comment "{r.section}:{r.name}"')
    # Services the host offers to the cloud (apt cache) must not leak to the Wi-Fi LAN.
    for proto, port in sorted(host_ports):
        lines.append(f'    iifname != "lo" {proto} dport {port} drop comment "zt: host service for mgmt only"')
    lines += ["  }", "}"]
    return "\n".join(lines) + "\n"


def render_libvirt_hook(policy: dict, env: dict, rules: list[Rule]) -> str:
    """libvirt's own NAT firewall (LIBVIRT_FWI) rejects NEW inbound traffic to a NAT network,
    and an accept in another nftables table cannot override a reject. This hook re-inserts
    the DNAT'd WireGuard flow at the top of libvirt's chain every time libvirt (re)builds it."""
    nets = policy["networks"]
    wg = [r for r in rules if r.src.name == "internet"]
    wan_bridge = nets["wan"]["bridge"]
    ipt, nft = [], []
    for r in wg:
        ipt.append(f'-i {env["wan_interface"]} -o {wan_bridge} -d {r.dst.addr}/32 -p {r.proto} '
                   f'--dport {r.port} -m conntrack --ctstate DNAT '
                   f'-m comment --comment zt:{r.name} -j ACCEPT')
        nft.append(f'iifname "{env["wan_interface"]}" oifname "{wan_bridge}" ip daddr {r.dst.addr} '
                   f'{r.proto} dport {r.port} ct status dnat counter accept comment "zt:{r.name}"')
    body = ["#!/bin/bash",
            GENERATED_HEADER.rstrip(),
            "# Installed as /etc/libvirt/hooks/network.d/zerotrust. Args: <network> <op> <sub-op>.",
            "# Also run by zerotrust-host.service at boot. Idempotent.",
            "set -u",
            'op="${2:-started}"',
            '[[ "$op" == "started" || "$op" == "reconnect" ]] || exit 0',
            "exec 0</dev/null",
            "",
            "# iptables backend (Ubuntu 24.04 default): chain LIBVIRT_FWI in table filter",
            "if iptables -w -n -L LIBVIRT_FWI >/dev/null 2>&1; then"]
    for rule in ipt:
        body += [f"  while iptables -w -D LIBVIRT_FWI {rule} 2>/dev/null; do :; done",
                 f"  iptables -w -I LIBVIRT_FWI 1 {rule}"]
    body += ["fi", "",
             "# nftables backend (newer libvirt): chain guest_input in table ip libvirt_network",
             "if nft list chain ip libvirt_network guest_input >/dev/null 2>&1; then"]
    for rule in nft:
        tag = rule.rsplit("comment ", 1)[1]
        body += [f"  for h in $(nft -a list chain ip libvirt_network guest_input | "
                 f"grep -F '{tag}' | sed -n 's/.*# handle //p'); do",
                 "    nft delete rule ip libvirt_network guest_input handle \"$h\"",
                 "  done",
                 f"  nft insert rule ip libvirt_network guest_input {rule}"]
    body += ["fi", "exit 0"]
    return "\n".join(body) + "\n"


def render_mtls(policy: dict, node: str, rules: list[Rule]) -> dict:
    serves, calls = {}, {}
    for r in rules:
        if not r.mtls:
            continue
        if r.dst.kind == "node" and r.dst.name == node:
            s = serves.setdefault(r.service, {
                "listen": f"{r.dst.addr}:{r.port}", "port": r.port, "allowed_ids": [],
                "allowed_sources": []})
            for i in r.allowed_ids:
                if i not in s["allowed_ids"]:
                    s["allowed_ids"].append(i)
            if r.src.addr not in s["allowed_sources"]:
                s["allowed_sources"].append(r.src.addr)
        if r.src.kind == "node" and r.src.name == node:
            calls[r.service] = {"address": f"{r.dst.addr}:{r.port}",
                                "expected_id": spiffe(policy, r.dst.name)}
    return {"node": node, "identity": spiffe(policy, node), "min_tls": policy["cert"]["min_tls"],
            "serves": serves, "calls": calls}


def render_pg_hba(policy: dict, rules: list[Rule]) -> str:
    lines = [GENERATED_HEADER.rstrip(),
             "# TYPE   DATABASE  USER  ADDRESS  METHOD",
             "local    all       postgres            peer",
             ]
    for r in rules:
        svc = policy["services"][r.service]
        if "db_user" in svc and r.src.kind == "node":
            lines.append(f"hostssl  {svc['db_name']}  {svc['db_user']}  {r.src.addr}/32  cert  "
                         f"clientcert=verify-full map=zt   # flows:{r.name}")
    lines.append("# everything else: no matching line -> rejected")
    return "\n".join(lines) + "\n"


def render_pg_ident(policy: dict, rules: list[Rule]) -> str:
    """Maps certificate CN (= node name) to the DB role. Only the declared caller."""
    lines = [GENERATED_HEADER.rstrip(), "# MAPNAME  SYSTEM-USERNAME(cert CN)  PG-USERNAME"]
    for r in rules:
        svc = policy["services"][r.service]
        if "db_user" in svc and r.src.kind == "node":
            lines.append(f"zt  {r.src.name}  {svc['db_user']}")
    return "\n".join(lines) + "\n"


def render_wireguard(policy: dict, env: dict) -> dict[str, str]:
    nets = policy["networks"]
    gw = next(n for n, s in policy["nodes"].items() if "tunnel" in s["interfaces"])
    gw_tun = policy["nodes"][gw]["interfaces"]["tunnel"]
    prefix = ipaddress.ip_network(nets["tunnel"]["cidr"]).prefixlen
    wg_svc = next(s for s in policy["services"].values() if s["node"] == gw and s["proto"] == "udp")
    # Clients only route what the policy lets them reach through the tunnel.
    reachable = sorted({f"{r.dst.addr}/32" for r in resolve(policy) if r.src.name == "tunnel"})
    out = {}
    srv = [GENERATED_HEADER.rstrip(), "[Interface]",
           f"Address = {gw_tun}/{prefix}", f"ListenPort = {wg_svc['port']}",
           "PrivateKey = {{ wg_keys['" + gw + "'].private }}", ""]
    for peer in policy["wireguard"]["peers"]:
        srv += [f"# peer: {peer['name']}", "[Peer]",
                "PublicKey = {{ wg_keys['" + peer["name"] + "'].public }}",
                "PresharedKey = {{ wg_keys['" + peer["name"] + "'].psk }}",
                f"AllowedIPs = {peer['ip']}/32", ""]
    out[f"{gw}-wg0.conf.j2"] = "\n".join(srv)
    for peer in policy["wireguard"]["peers"]:
        cli = [GENERATED_HEADER.rstrip(), f"# client: {peer['name']}", "[Interface]",
               f"Address = {peer['ip']}/32",
               "PrivateKey = {{ wg_keys['" + peer["name"] + "'].private }}", "",
               "[Peer]",
               "PublicKey = {{ wg_keys['" + gw + "'].public }}",
               "PresharedKey = {{ wg_keys['" + peer["name"] + "'].psk }}",
               f"Endpoint = {env['entry_point']}:{int(env['wan_port'])}",
               f"AllowedIPs = {', '.join(reachable)}",
               "PersistentKeepalive = 25", ""]
        out[f"client-{peer['name']}.conf.j2"] = "\n".join(cli)
    return out


def _mac(net_index: int, node_id: int) -> str:
    return f"52:54:00:5a:{net_index:02x}:{node_id:02x}"


def render_tfvars(policy: dict, env: dict) -> dict:
    nets = policy["networks"]
    net_order = [n for n in nets if nets[n]["mode"] != "wireguard"]
    networks = {}
    for i, n in enumerate(net_order):
        spec = nets[n]
        cidr = ipaddress.ip_network(spec["cidr"])
        networks[n] = {"name": f"zt-{n}", "mode": spec["mode"], "cidr": str(cidr),
                       "bridge": spec["bridge"], "host_ip": spec.get("host_ip"),
                       "prefix": cidr.prefixlen}
    nodes = {}
    for name, spec in policy["nodes"].items():
        ifaces = []
        for i, n in enumerate(net_order):
            if n in spec["interfaces"]:
                cidr = ipaddress.ip_network(nets[n]["cidr"])
                routes = [{"to": "default", "via": spec["default_gateway"]["via"]}
                          ] if spec.get("default_gateway", {}).get("network") == n else []
                # each static route is attached to the interface whose network holds its next hop
                routes += [{"to": r["to"], "via": r["via"]} for r in spec.get("routes", [])
                           if ipaddress.ip_address(r["via"]) in cidr]
                ifaces.append({"network": n, "ip": spec["interfaces"][n], "iface": nets[n]["iface"],
                               "mac": _mac(i + 1, spec["id"]), "prefix": networks[n]["prefix"],
                               "routes": routes})
        nodes[name] = {"memory_mb": spec["memory_mb"], "interfaces": ifaces,
                       "ip_forward": bool(spec.get("ip_forward"))}
    return {"libvirt_uri": env["libvirt_uri"], "pool_name": env["libvirt_pool_name"],
            "pool_path": env["libvirt_pool_path"], "image_url": env["ubuntu_image_url"],
            "ssh_user": env["ssh_user"], "ssh_public_key_file": env["ssh_public_key_file"],
            "apt_proxy": f"http://{nets['mgmt']['host_ip']}:"
                         f"{policy['services']['apt-cache']['port']}"
                         if "apt-cache" in policy["services"] else "",
            "networks": networks, "nodes": nodes}


def render_inventory(policy: dict, env: dict) -> dict:
    hosts = {n: {"ansible_host": s["interfaces"]["mgmt"], "zt_id": s["id"]}
             for n, s in policy["nodes"].items()}
    return {"all": {"vars": {"ansible_user": env["ssh_user"],
                             "ansible_ssh_private_key_file": private_key_file(env),
                             "ansible_python_interpreter": "/usr/bin/python3"},
                    "hosts": hosts}}


def private_key_file(env: dict) -> str:
    return str(env["ssh_public_key_file"])[: -len(".pub")]


def render_ssh_config(policy: dict, env: dict) -> str:
    """`ssh -F build/ssh_config <node>` — mgmt network only. VMs are re-created often and
    live on an isolated host-only bridge, so their host keys are not pinned."""
    lines = [GENERATED_HEADER.rstrip()]
    for n, s in policy["nodes"].items():
        lines += [f"Host {n}", f"  HostName {s['interfaces']['mgmt']}", f"  User {env['ssh_user']}",
                  f"  IdentityFile {private_key_file(env)}", "  IdentitiesOnly yes",
                  "  StrictHostKeyChecking no", "  UserKnownHostsFile /dev/null",
                  "  LogLevel ERROR", "  ConnectTimeout 5", ""]
    return "\n".join(lines)


def render_matrix(policy: dict, rules: list[Rule]) -> list[dict]:
    """Every source x every listening (node, ip, port). Expected = allow iff a rule matches."""
    allowed = {(r.src.name, r.dst.addr, r.port, r.proto): r.name for r in rules}
    sources = []
    for n, s in policy["nodes"].items():
        sources.append({"name": n, "kind": "node"})
    # Probe-able principals: test-peer stands in for "tunnel", the i5 for "host".
    peers = {p["name"]: p["ip"] for p in policy.get("wireguard", {}).get("peers", [])}
    if "tunnel" in policy["principals"] and "test-peer" in peers:
        sources.append({"name": "tunnel", "kind": "principal", "probe_ip": peers["test-peer"]})
    if "host" in policy["principals"]:
        sources.append({"name": "host", "kind": "principal",
                        "probe_ip": policy["principals"]["host"]["cidr"].split("/")[0]})
    targets = []
    for svc_name, svc in policy["services"].items():
        if svc["node"] == "host":
            targets.append(("host", policy["networks"][svc["network"]]["host_ip"], svc_name, svc))
            continue
        for node in (policy["nodes"] if svc["node"] == "*" else [svc["node"]]):
            # Probe the port on EVERY address of the node, not just the one it listens on:
            # this catches a service accidentally bound to 0.0.0.0 behind a leaky firewall.
            for net, ip in policy["nodes"][node]["interfaces"].items():
                targets.append((node, ip, svc_name, svc))
    matrix = []
    for src in sources:
        for node, ip, svc_name, svc in targets:
            if src["name"] == node:
                continue
            key = (src["name"], ip, svc["port"], svc["proto"])
            matrix.append({"src": src["name"], "src_kind": src["kind"],
                           "probe_ip": src.get("probe_ip"),
                           "dst": node, "dst_ip": ip, "service": svc_name,
                           "port": svc["port"], "proto": svc["proto"],
                           "expected": "allow" if key in allowed else "deny",
                           "flow": allowed.get(key)})
    return matrix


